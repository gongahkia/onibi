use std::{fs, path::PathBuf};

fn workspace_file(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(name)
}

#[test]
fn pins_toolchain_and_tracks_lockfile() {
    let toolchain = fs::read_to_string(workspace_file("rust-toolchain.toml"))
        .expect("workspace must include rust-toolchain.toml");
    assert!(
        toolchain.contains("channel = \"1.93.0\""),
        "toolchain must use an exact Rust release"
    );
    assert!(
        toolchain.contains("components = [\"clippy\", \"rustfmt\"]"),
        "toolchain must install CI components"
    );
    assert!(
        toolchain.contains("profile = \"minimal\""),
        "toolchain must use the minimal profile"
    );

    let lockfile =
        fs::read_to_string(workspace_file("Cargo.lock")).expect("workspace must track Cargo.lock");
    assert!(
        lockfile.starts_with("# This file is automatically @generated by Cargo."),
        "Cargo.lock must be a Cargo-generated lockfile"
    );
}

#[test]
fn grpc_codegen_uses_the_pinned_vendored_protobuf_compiler() {
    let workspace_manifest = fs::read_to_string(workspace_file("Cargo.toml"))
        .expect("workspace must include Cargo.toml");
    assert!(workspace_manifest.contains("protoc-bin-vendored = \"=3.2.0\""));

    for package in ["yeokcham-daemon-api", "yeokcham-relay-api"] {
        let manifest = fs::read_to_string(workspace_file(&format!("crates/{package}/Cargo.toml")))
            .expect("generated API crate must include Cargo.toml");
        assert!(manifest.contains("protoc-bin-vendored.workspace = true"));

        let build_script =
            fs::read_to_string(workspace_file(&format!("crates/{package}/build.rs")))
                .expect("generated API crate must include build.rs");
        assert!(build_script.contains("protoc_bin_vendored::protoc_bin_path()?"));
        assert!(build_script.contains("config.protoc_executable(protoc);"));
        assert!(build_script.contains(".compile_with_config("));
    }
}

#[test]
fn workspace_features_are_explicitly_opt_in() {
    let policy = fs::read_to_string(workspace_file("FEATURES.md"))
        .expect("workspace must document feature policy");
    assert!(policy.contains("default = []"));
    assert!(policy.contains("must be additive"));

    for package in [
        "yeokcham-cli",
        "yeokcham-core",
        "yeokcham-daemon",
        "yeokcham-ffi",
        "yeokcham-protocol",
        "yeokcham-relay",
    ] {
        let manifest = fs::read_to_string(workspace_file(&format!("crates/{package}/Cargo.toml")))
            .expect("workspace crate must include Cargo.toml");
        assert!(
            manifest.contains("[features]\ndefault = []"),
            "{package} must keep all features opt-in"
        );
    }
}

#[test]
fn api_version_policy_limits_publishable_rust_surface() {
    let policy = fs::read_to_string(workspace_file("API_COMPATIBILITY.md"))
        .expect("workspace must document its public API policy");
    for section in [
        "## Public interfaces",
        "## Versioning rules",
        "## Compatibility checks",
        "yeokcham-sdk",
        "YEOKCHAM_ABI_VERSION",
        "PROTOCOL_COMPATIBILITY.md",
    ] {
        assert!(
            policy.contains(section),
            "API policy must document {section}"
        );
    }

    for package in [
        "yeokcham-cli",
        "yeokcham-core",
        "yeokcham-daemon",
        "yeokcham-daemon-api",
        "yeokcham-ffi",
        "yeokcham-protocol",
        "yeokcham-relay",
    ] {
        let manifest = fs::read_to_string(workspace_file(&format!("crates/{package}/Cargo.toml")))
            .expect("workspace crate must include Cargo.toml");
        assert!(
            manifest.contains("publish = false"),
            "{package} must remain an internal Rust crate"
        );
    }

    let sdk_manifest = fs::read_to_string(workspace_file("crates/yeokcham-sdk/Cargo.toml"))
        .expect("SDK crate must include Cargo.toml");
    assert!(
        !sdk_manifest.contains("publish = false"),
        "SDK must remain the publishable Rust API"
    );
}

