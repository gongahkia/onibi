import { readFile, writeFile } from "node:fs/promises";

const schemaUrl = new URL("../packages/pi-agent/schema/envelope.schema.json", import.meta.url);
const outputUrl = new URL("../packages/pi-agent/schema/envelope.types.ts", import.meta.url);
const schema = JSON.parse(await readFile(schemaUrl, "utf8"));

const required = ["msg_id", "ts", "sender", "kind", "payload", "sig"];
const missing = required.filter((field) => !schema.required?.includes(field));
if (missing.length > 0) {
  throw new Error(`Envelope schema missing required fields: ${missing.join(", ")}`);
}

const senderValues = schema.properties?.sender?.enum;
if (!Array.isArray(senderValues) || senderValues.length === 0) {
  throw new Error("Envelope schema must define sender enum values.");
}

const senderType = senderValues.map((value) => JSON.stringify(value)).join(" | ");
const kindValues = schema.properties?.kind?.enum;
if (!Array.isArray(kindValues) || kindValues.length === 0) {
  throw new Error("Envelope schema must define kind enum values.");
}

const kindType = kindValues.map((value) => `  | ${JSON.stringify(value)}`).join("\n");

const source = `// Generated by scripts/generate-pi-protocol-types.mjs. Do not edit by hand.

export type PiEnvelopeSender = ${senderType};
export type PiEnvelopeKind =
${kindType};

export type JsonPrimitive = string | number | boolean | null;
export type JsonValue =
  | JsonPrimitive
  | readonly JsonValue[]
  | { readonly [key: string]: JsonValue };
export type JsonRecord = { readonly [key: string]: JsonValue };

export interface PiWireEnvelope {
  readonly msg_id: string;
  readonly ts: string;
  readonly sender: PiEnvelopeSender;
  readonly kind: PiEnvelopeKind;
  readonly payload: JsonRecord;
  readonly sig: string;
}

export const piWireEnvelopeSchemaId =
  ${JSON.stringify(schema.$id)} as const;
`;

await writeFile(outputUrl, source);
